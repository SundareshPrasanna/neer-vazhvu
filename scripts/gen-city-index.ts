/**
 * Builds the city index in src/cities/generated/ from the city folders.
 *
 * A city is a folder, src/cities/<id>/. This script finds every folder, reads
 * its config.ts, and writes the files the app imports instead of hand-kept
 * lists: the city ids in list order, the config registry, the About and
 * Origins loaders, one map per optional module (MODULES below), and
 * cities.json (every config as plain JSON, for Python scripts and workflows;
 * read it through scripts/city_manifest.py). Adding a city or a
 * story language never means editing a shared file; it means running this.
 *
 *   npm run cities:gen            write src/cities/generated/
 *   npm run cities:gen -- --check exit 1 if the committed files are stale
 *
 * It also appends a row to schemas/nvdm/scopes.json for a city that has none
 * (the registry is append-only, so existing rows are never rewritten). The
 * row's parent is the state scope whose ISO 3166-2 code is IN-<stateCode>; if
 * that state is not registered yet, the script stops and says so. After a row
 * is added, run `python3 scripts/build_nvdm_reference.py`.
 *
 * src/cities/generated.test.ts runs the same check inside `npm test`.
 *
 * What it expects in each folder (see src/cities/README.md):
 *   config.ts       required; `export default` a PlaceConfig whose cityId is the folder name
 *   about.tsx       required; `export default` the About slot component
 *   story-<lang>.tsx  optional; `export default` the Origins story; story-en.tsx first
 *   any file in MODULES, optional; exports the named constant
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = resolve(__dirname, "..");
const CITIES_DIR = join(ROOT, "src/cities");
const OUT_DIR = join(CITIES_DIR, "generated");
const SCOPES = join(ROOT, "schemas/nvdm/scopes.json");
const HEADER =
  "// Generated by scripts/gen-city-index.ts from the folders in src/cities/.\n" +
  "// Do not edit by hand: run `npm run cities:gen`.\n";

/** Optional per-city modules. Each is a file in the city's folder that exports
 *  one constant; the generator collects them into src/cities/generated/<file>.ts
 *  as one map keyed by city id. A new kind of per-city content is one line here. */
export const MODULES = [
  { file: "rivers", exportName: "RIVERS", map: "RIVERS_CONTENT", type: "CityRiversContent",
    typeFrom: "../../content/rivers/types", doc: "/[cityId]/rivers content (rivers.ts)." },
  { file: "flood", exportName: "FLOOD", map: "FLOOD_CONTENT", type: "CityFloodContent",
    typeFrom: "../../content/flood/types", doc: "/[cityId]/flood-risk content (flood.ts or flood.tsx)." },
  { file: "my-ward", exportName: "MY_WARD", map: "MY_WARD_CONTENT", type: "CityMyWardContent",
    typeFrom: "../../content/my-ward/types", doc: "My Ward source lines, quick actions and helplines (my-ward.ts)." },
  { file: "routes-off", exportName: "ROUTES_OFF", map: "ROUTES_OFF_BY_CITY", type: "RoutesOff",
    typeFrom: "../../content/routes-off", doc: "Why each city leaves out the routes it does not ship (routes-off.ts). Read by the exemptions register." },
] as const;

export interface CityFolder {
  id: string;
  listOrder: number;
  config: Record<string, unknown>;
  stories: string[];
  /** The MODULES files this folder has. */
  modules: string[];
}

/** `navi-mumbai` -> `naviMumbai`, for import names. */
function ident(id: string): string {
  return id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

function key(id: string): string {
  return /^[a-z][a-z0-9]*$/.test(id) ? id : JSON.stringify(id);
}

export async function scanCities(dir = CITIES_DIR): Promise<CityFolder[]> {
  const problems: string[] = [];
  const cities: CityFolder[] = [];
  const folders = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name !== "generated")
    .map((d) => d.name)
    .sort();
  for (const id of folders) {
    const folder = join(dir, id);
    const files = new Set(readdirSync(folder));
    if (!/^[a-z][a-z0-9-]*$/.test(id)) problems.push(`${id}: folder names are lowercase ids (a-z, 0-9, -)`);
    if (!files.has("config.ts")) {
      problems.push(`${id}: no config.ts`);
      continue;
    }
    if (!files.has("about.tsx")) problems.push(`${id}: no about.tsx (every city has an About page)`);
    const mod = await import(pathToFileURL(join(folder, "config.ts")).href);
    const config = mod.default?.default ?? mod.default;
    if (!config || typeof config !== "object") {
      problems.push(`${id}: config.ts has no default export`);
      continue;
    }
    if (config.cityId !== id) problems.push(`${id}: config.cityId is "${config.cityId}", expected the folder name`);
    if (!Number.isInteger(config.listOrder)) problems.push(`${id}: listOrder must be an integer`);
    const stories = [...files]
      .map((f) => /^story-([a-z]{2,3})\.tsx$/.exec(f)?.[1])
      .filter((l): l is string => Boolean(l))
      .sort((a, b) => (a === "en" ? -1 : b === "en" ? 1 : a.localeCompare(b)));
    if (stories.length > 0 && stories[0] !== "en") problems.push(`${id}: has a story but no story-en.tsx`);
    for (const lang of stories) {
      const src = readFileSync(join(folder, `story-${lang}.tsx`), "utf8");
      if (!/^export default /m.test(src)) problems.push(`${id}: story-${lang}.tsx needs an \`export default\``);
    }
    cities.push({
      id,
      listOrder: config.listOrder,
      config,
      stories,
      modules: MODULES.filter((m) => files.has(`${m.file}.ts`) || files.has(`${m.file}.tsx`)).map((m) => m.file),
    });
  }
  const seen = new Map<number, string>();
  for (const c of cities) {
    const other = seen.get(c.listOrder);
    if (other) problems.push(`${c.id}: listOrder ${c.listOrder} is already taken by ${other}`);
    seen.set(c.listOrder, c.id);
  }
  if (problems.length) throw new Error(`src/cities/ has problems:\n  ${problems.join("\n  ")}`);
  return cities.sort((a, b) => a.listOrder - b.listOrder);
}

export function renderIndex(cities: CityFolder[]): Record<string, string> {
  const ids = `${HEADER}
/** Every registered city, in list order. */
export const CITY_IDS = [
${cities.map((c) => `  ${JSON.stringify(c.id)},`).join("\n")}
] as const;
`;

  const registry = `${HEADER}
import type { CityId } from "../../lib/cities/ids";
import type { PlaceConfig } from "../../lib/cities/types";
${cities.map((c) => `import ${ident(c.id)} from "../${c.id}/config";`).join("\n")}

/** Every city's config, keyed by id. Read it through src/lib/cities. */
export const CITY_CONFIGS: Record<CityId, PlaceConfig> = {
${cities.map((c) => `  ${key(c.id)}: ${ident(c.id)},`).join("\n")}
};
`;

  const modules: Record<string, string> = {};
  for (const m of MODULES) {
    const has = cities.filter((c) => c.modules.includes(m.file));
    modules[`${m.file}.ts`] = `${HEADER}
import type { CityId } from "../../lib/cities/ids";
import type { ${m.type} } from "${m.typeFrom}";
${has.map((c) => `import { ${m.exportName} as ${ident(c.id)} } from "../${c.id}/${m.file}";`).join("\n")}

/** ${m.doc} */
export const ${m.map}: Partial<Record<CityId, ${m.type}>> = {
${has.map((c) => `  ${key(c.id)}: ${ident(c.id)},`).join("\n")}
};
`;
  }

  const withStories = cities.filter((c) => c.stories.length);
  const pages = `"use client";

${HEADER}
import dynamic from "next/dynamic";
import type { ComponentType } from "react";
import type { CityId } from "../../lib/cities/ids";
import type { LanguageCode } from "../../lib/i18n/translations";
import type { CityAboutSlotProps } from "../../components/about/city-about";

/** Each city's About page (src/cities/<id>/about.tsx), loaded only on that city's page. */
export const CITY_ABOUT: Record<CityId, ComponentType<CityAboutSlotProps>> = {
${cities.map((c) => `  ${key(c.id)}: dynamic(() => import("../${c.id}/about")),`).join("\n")}
};

/** Each city's Origins story per language (src/cities/<id>/story-<lang>.tsx). */
export const CITY_STORIES: Partial<
  Record<CityId, { en: ComponentType } & Partial<Record<LanguageCode, ComponentType>>>
> = {
${withStories
  .map(
    (c) =>
      `  ${key(c.id)}: {\n${c.stories
        .map((l) => `    ${l}: dynamic(() => import("../${c.id}/story-${l}")),`)
        .join("\n")}\n  },`,
  )
  .join("\n")}
};
`;

  const json = `${JSON.stringify(Object.fromEntries(cities.map((c) => [c.id, c.config])), null, 2)}\n`;

  return { "ids.ts": ids, "registry.ts": registry, "pages.tsx": pages, ...modules, "cities.json": json };
}

interface ScopeRow {
  kind: string;
  name: string;
  refs?: { system: string; level?: string; code: string }[];
}

/** scopes.json with a row appended for every city that lacks one, or null when
 *  none is missing. Rows are inserted after the last city or region row, in
 *  the file's one-line-per-scope format. */
export function withMissingScopes(cities: CityFolder[], text = readFileSync(SCOPES, "utf8")): string | null {
  const scopes: Record<string, ScopeRow> = JSON.parse(text).scopes;
  const missing = cities.filter((c) => !(c.id in scopes));
  if (!missing.length) return null;
  const lines = text.split("\n");
  const lastPlace = lines.reduce(
    (at, line, i) => (/^  "[^"]+": \{"kind": "(city|region)"/.test(line) ? i : at),
    -1,
  );
  const rows = missing.map((c) => {
    const code = `IN-${c.config.stateCode}`;
    const state = Object.entries(scopes).find(
      ([, s]) => s.kind === "state" && s.refs?.some((r) => r.system === "iso3166-2" && r.code === code),
    )?.[0];
    if (!state) {
      throw new Error(
        `${c.id}: schemas/nvdm/scopes.json has no state scope with iso3166-2 ${code}. ` +
          "Add the state's row first (see the existing state rows), then run this again.",
      );
    }
    const kind = (c.config.placeKind as string | undefined) ?? "city";
    return `  ${JSON.stringify(c.id)}: {"kind": ${JSON.stringify(kind)}, "name": ${JSON.stringify(c.config.displayName)}, "relations": [{"type": "administrative-parent", "target": ${JSON.stringify(state)}}]},`;
  });
  lines.splice(lastPlace + 1, 0, ...rows);
  const out = lines.join("\n");
  JSON.parse(out); // a row added after the object's last entry would leave a trailing comma
  return out;
}

/** Files in src/cities/generated/ that are out of date or no longer generated.
 *  Empty when the index is current. */
export async function staleFiles(): Promise<string[]> {
  const files = renderIndex(await scanCities());
  const changed = Object.entries(files)
    .filter(([name, text]) => {
      const path = join(OUT_DIR, name);
      return !existsSync(path) || readFileSync(path, "utf8") !== text;
    })
    .map(([name]) => name);
  const leftover = existsSync(OUT_DIR) ? readdirSync(OUT_DIR).filter((f) => !(f in files)) : [];
  const scopes = withMissingScopes(await scanCities()) ? ["schemas/nvdm/scopes.json (city rows)"] : [];
  return [...changed, ...leftover, ...scopes];
}

async function main() {
  if (process.argv.includes("--check")) {
    const stale = await staleFiles();
    if (stale.length) {
      console.error(`src/cities/generated/ is out of date (${stale.join(", ")}). Run: npm run cities:gen`);
      process.exit(1);
    }
    console.log("src/cities/generated/ is current");
    return;
  }
  const cities = await scanCities();
  const files = renderIndex(cities);
  mkdirSync(OUT_DIR, { recursive: true });
  for (const f of readdirSync(OUT_DIR)) if (!(f in files)) rmSync(join(OUT_DIR, f));
  for (const [name, text] of Object.entries(files)) writeFileSync(join(OUT_DIR, name), text);
  console.log(`wrote ${Object.keys(files).length} files to src/cities/generated/`);
  const scopes = withMissingScopes(cities);
  if (scopes) {
    writeFileSync(SCOPES, scopes);
    console.log("added city rows to schemas/nvdm/scopes.json; now run: python3 scripts/build_nvdm_reference.py");
  }
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
