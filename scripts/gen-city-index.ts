/**
 * Builds the city index in src/cities/generated/ from the city folders.
 *
 * A city is a folder, src/cities/<id>/. This script finds every folder, reads
 * its config.ts, and writes the files the app imports instead of hand-kept
 * lists: the city ids in launch order, the config registry, the rivers and
 * flood content maps, the About and Origins loaders, and cities.json (every
 * config as plain JSON, for Python scripts and workflows; read it through
 * scripts/city_manifest.py). Adding a city or a
 * story language never means editing a shared file; it means running this.
 *
 *   npm run cities:gen            write src/cities/generated/
 *   npm run cities:gen -- --check exit 1 if the committed files are stale
 *
 * src/cities/generated.test.ts runs the same check inside `npm test`.
 *
 * What it expects in each folder (see src/cities/README.md):
 *   config.ts       required; `export default` a PlaceConfig whose cityId is the folder name
 *   about.tsx       required; `export default` the About slot component
 *   story-<lang>.tsx  optional; `export default` the Origins story; story-en.tsx first
 *   rivers.ts       optional; exports RIVERS
 *   flood.ts(x)     optional; exports FLOOD
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = resolve(__dirname, "..");
const CITIES_DIR = join(ROOT, "src/cities");
const OUT_DIR = join(CITIES_DIR, "generated");
const HEADER =
  "// Generated by scripts/gen-city-index.ts from the folders in src/cities/.\n" +
  "// Do not edit by hand: run `npm run cities:gen`.\n";

export interface CityFolder {
  id: string;
  launchOrder: number;
  config: Record<string, unknown>;
  stories: string[];
  rivers: boolean;
  flood: boolean;
}

/** `navi-mumbai` -> `naviMumbai`, for import names. */
function ident(id: string): string {
  return id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

function key(id: string): string {
  return /^[a-z][a-z0-9]*$/.test(id) ? id : JSON.stringify(id);
}

export async function scanCities(dir = CITIES_DIR): Promise<CityFolder[]> {
  const problems: string[] = [];
  const cities: CityFolder[] = [];
  const folders = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name !== "generated")
    .map((d) => d.name)
    .sort();
  for (const id of folders) {
    const folder = join(dir, id);
    const files = new Set(readdirSync(folder));
    if (!/^[a-z][a-z0-9-]*$/.test(id)) problems.push(`${id}: folder names are lowercase ids (a-z, 0-9, -)`);
    if (!files.has("config.ts")) {
      problems.push(`${id}: no config.ts`);
      continue;
    }
    if (!files.has("about.tsx")) problems.push(`${id}: no about.tsx (every city has an About page)`);
    const mod = await import(pathToFileURL(join(folder, "config.ts")).href);
    const config = mod.default?.default ?? mod.default;
    if (!config || typeof config !== "object") {
      problems.push(`${id}: config.ts has no default export`);
      continue;
    }
    if (config.cityId !== id) problems.push(`${id}: config.cityId is "${config.cityId}", expected the folder name`);
    if (!Number.isInteger(config.launchOrder)) problems.push(`${id}: launchOrder must be an integer`);
    const stories = [...files]
      .map((f) => /^story-([a-z]{2,3})\.tsx$/.exec(f)?.[1])
      .filter((l): l is string => Boolean(l))
      .sort((a, b) => (a === "en" ? -1 : b === "en" ? 1 : a.localeCompare(b)));
    if (stories.length > 0 && stories[0] !== "en") problems.push(`${id}: has a story but no story-en.tsx`);
    for (const lang of stories) {
      const src = readFileSync(join(folder, `story-${lang}.tsx`), "utf8");
      if (!/^export default /m.test(src)) problems.push(`${id}: story-${lang}.tsx needs an \`export default\``);
    }
    cities.push({
      id,
      launchOrder: config.launchOrder,
      config,
      stories,
      rivers: files.has("rivers.ts"),
      flood: files.has("flood.ts") || files.has("flood.tsx"),
    });
  }
  const seen = new Map<number, string>();
  for (const c of cities) {
    const other = seen.get(c.launchOrder);
    if (other) problems.push(`${c.id}: launchOrder ${c.launchOrder} is already taken by ${other}`);
    seen.set(c.launchOrder, c.id);
  }
  if (problems.length) throw new Error(`src/cities/ has problems:\n  ${problems.join("\n  ")}`);
  return cities.sort((a, b) => a.launchOrder - b.launchOrder);
}

export function renderIndex(cities: CityFolder[]): Record<string, string> {
  const ids = `${HEADER}
/** Every registered city, in launch order. */
export const CITY_IDS = [
${cities.map((c) => `  ${JSON.stringify(c.id)},`).join("\n")}
] as const;
`;

  const registry = `${HEADER}
import type { CityId } from "../../lib/cities/ids";
import type { PlaceConfig } from "../../lib/cities/types";
${cities.map((c) => `import ${ident(c.id)} from "../${c.id}/config";`).join("\n")}

/** Every city's config, keyed by id. Read it through src/lib/cities. */
export const CITY_CONFIGS: Record<CityId, PlaceConfig> = {
${cities.map((c) => `  ${key(c.id)}: ${ident(c.id)},`).join("\n")}
};
`;

  const withRivers = cities.filter((c) => c.rivers);
  const withFlood = cities.filter((c) => c.flood);
  const content = `${HEADER}
import type { CityId } from "../../lib/cities/ids";
import type { CityRiversContent } from "../../content/rivers/types";
import type { CityFloodContent } from "../../content/flood/types";
${withRivers.map((c) => `import { RIVERS as ${ident(c.id)}Rivers } from "../${c.id}/rivers";`).join("\n")}
${withFlood.map((c) => `import { FLOOD as ${ident(c.id)}Flood } from "../${c.id}/flood";`).join("\n")}

/** /[cityId]/rivers content (src/cities/<id>/rivers.ts). */
export const RIVERS_CONTENT: Partial<Record<CityId, CityRiversContent>> = {
${withRivers.map((c) => `  ${key(c.id)}: ${ident(c.id)}Rivers,`).join("\n")}
};

/** /[cityId]/flood-risk content (src/cities/<id>/flood.ts or flood.tsx). */
export const FLOOD_CONTENT: Partial<Record<CityId, CityFloodContent>> = {
${withFlood.map((c) => `  ${key(c.id)}: ${ident(c.id)}Flood,`).join("\n")}
};
`;

  const withStories = cities.filter((c) => c.stories.length);
  const pages = `"use client";

${HEADER}
import dynamic from "next/dynamic";
import type { ComponentType } from "react";
import type { CityId } from "../../lib/cities/ids";
import type { LanguageCode } from "../../lib/i18n/translations";
import type { CityAboutSlotProps } from "../../components/about/city-about";

/** Each city's About page (src/cities/<id>/about.tsx), loaded only on that city's page. */
export const CITY_ABOUT: Record<CityId, ComponentType<CityAboutSlotProps>> = {
${cities.map((c) => `  ${key(c.id)}: dynamic(() => import("../${c.id}/about")),`).join("\n")}
};

/** Each city's Origins story per language (src/cities/<id>/story-<lang>.tsx). */
export const CITY_STORIES: Partial<
  Record<CityId, { en: ComponentType } & Partial<Record<LanguageCode, ComponentType>>>
> = {
${withStories
  .map(
    (c) =>
      `  ${key(c.id)}: {\n${c.stories
        .map((l) => `    ${l}: dynamic(() => import("../${c.id}/story-${l}")),`)
        .join("\n")}\n  },`,
  )
  .join("\n")}
};
`;

  const json = `${JSON.stringify(Object.fromEntries(cities.map((c) => [c.id, c.config])), null, 2)}\n`;

  return { "ids.ts": ids, "registry.ts": registry, "content.ts": content, "pages.tsx": pages, "cities.json": json };
}

/** The files that are out of date, by name. Empty when the index is current. */
export async function staleFiles(): Promise<string[]> {
  const files = renderIndex(await scanCities());
  return Object.entries(files)
    .filter(([name, text]) => {
      const path = join(OUT_DIR, name);
      return !existsSync(path) || readFileSync(path, "utf8") !== text;
    })
    .map(([name]) => name);
}

async function main() {
  if (process.argv.includes("--check")) {
    const stale = await staleFiles();
    if (stale.length) {
      console.error(`src/cities/generated/ is out of date (${stale.join(", ")}). Run: npm run cities:gen`);
      process.exit(1);
    }
    console.log("src/cities/generated/ is current");
    return;
  }
  const files = renderIndex(await scanCities());
  mkdirSync(OUT_DIR, { recursive: true });
  for (const [name, text] of Object.entries(files)) writeFileSync(join(OUT_DIR, name), text);
  console.log(`wrote ${Object.keys(files).length} files to src/cities/generated/`);
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
