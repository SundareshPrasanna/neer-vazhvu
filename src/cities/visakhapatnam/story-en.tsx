        <p>
          In 2003 the corporation took up what it called the Godavari Drinking
          Water Supply Project, designed for 33 million gallons a day. It paid
          for it partly with Rs 65 crore of municipal bonds and spent about Rs
          135.5 crore on it across 2003-04 and 2004-05, by its own accounts. In
          2003-04 it also lent the state industrial corporation, APIIC, Rs 60
          crore and invested Rs 7.5 crore in the Visakhapatnam Industrial Water
          Supply Company, set up to carry water to industry along the Yeleru
          canal. A government order of 10 September 2004, as cited by the
          corporation in a 2016 document prepared for the Asian Development
          Bank, allocated 24 TMC from the left canal of the Polavaram project,
          which had yet to be built, for the city&apos;s homes and industries.
          The industrial water company says it completed a 56 kilometre
          pipeline from a pump house on the Godavari at Kateru to the Yeleru
          canal on 24 December 2004, and began operating it the next day.
        </p>
