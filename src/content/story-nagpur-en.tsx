        <p>
          The Nag is the way out; the 1966 Gazetteer already wrote that the
          city &ldquo;has a fair natural drainage in the Nag river&rdquo;. In
          2023-24, by NMC&apos;s figures, there was about 520 million litres a
          day of sewage, which the report estimates as 73% of the water
          supplied, and 403.5 million litres a day was treated at 12 plants. The same report finds that as
          the Nag &ldquo;flows through the city, the pollution load goes on
          increasing&rdquo;.
        </p>
