        <p>
          மதுரையின் நீர் நிலை தமிழ்நாட்டில் சிறப்பாக ஆவணப்படுத்தப்பட்ட
          ஒன்று. பாண்டியர் கல்வெட்டுகள் கண்மாய்களை பெயரிட்டன. 1906
          மெட்ராஸ் மாவட்ட கெஜட்டியர் அவற்றை வரைபடப்படுத்தியது. டேவிட்
          மோஸ்-ன் இனவியல் (<em>The Rule of Water</em>, ஆக்ஸ்போர்டு,
          2003) அவற்றின் நிறுவன அதிகாரம் எப்படி அவிழ்ந்தது என்பதை
          கண்டறிந்தது. K. சிவசுப்பிரமணியனின் 2007 ஆய்வுக்கட்டுரை
          1961 முதல் தமிழ்நாடு-முழுவதும் கண்மாய்-நீர்ப்பாசன பரப்பின்
          வீழ்ச்சியை அளவீடு செய்தது. 2020-21 சக-மதிப்பாய்வு செய்யப்பட்ட
          வண்டியூர் அடுக்கு ஆய்வு (Sashikkumar et al.,{" "}
          <em>Discover Applied Sciences</em>) மதுரையின் முதன்மையான
          எஞ்சிய வலையமைப்பில் ஆழ்துளைக் கிணற்றின் ஆழங்களைக்
          கண்காணித்தது: 1990-களின் ஆரம்பத்தில் சுமார் எட்டு மீட்டர்,
          2007-ல் அறுபது மீட்டர், 2017-18-ல் இருநூறு மீட்டர். இந்தியா
          வாட்டர் போர்ட்டலின் களப் பயணங்கள் 2002 முதல் 2018 வரை
          நகர்-புறப்பகுதி நில-மூடி 300% அதிகரித்ததைப் பதிவுசெய்தன,
          அதே காலகட்டத்தில் பருவமழை வடகிழக்கில் 11.2% மற்றும் தென்மேற்கில்
          10.6% குறைந்துள்ளது. மொன்காபே இந்தியாவின் 2021 வைகை சிறப்புக்
          கட்டுரை, வைகை அணையின் நீரில் சுமார் எண்பத்தைந்து சதவீதம்
          இப்போது கேரளாவின் பெரியார் நீர்ப்பிடிப்பிலிருந்து முல்லைப்
          பெரியார் சுரங்கப்பாதை வழியாக வருகிறது என்பதை நிறுவியது -
          வைகையின் சொந்த நீர்ப்பிடிப்பு வெறும் பதினைந்து சதவீதத்தை
          மட்டுமே வழங்குகிறது. கொலம்பியா GSAPP மற்றும் தியாகராஜர்
          பொறியியல் கல்லூரி ஸ்டுடியோ (<em>Water Urbanism in Madurai</em>,
          2016) இந்த வரிசையில் ஒரு உள்ளீடு, அதன் அடித்தளம் அல்ல.
        </p>
