        <p>
          இரண்டாயிரம் ஆண்டுகள் நிற்கும் நகரம் ஒரு தனிப்பட்ட சொத்து
          அல்ல. அது நமக்குக் கொடுக்கப்பட்டது. நாம் நீதிமன்றங்களைக் கட்டிய
          கண்மாய்கள் நாம் புதைக்க உரிமையற்றவை. நாம் படுகையை அள்ளி
          உடைத்த ஆறு நாம் உடைக்க உரிமை இல்லாதது.{" "}
          <em>குடிமராமத்து</em> என்னும் கடமை - அடுக்கைப் பயன்படுத்தியவர்கள்
          அதன் பராமரிப்பை கடமையாக ஏற்றிருந்தது - காலனிய அலுவலகம்
          பதிவுசெய்வதை நிறுத்தியபோது முடிந்துவிடவில்லை. நாம் வெறுமனே
          செலுத்துவதை நிறுத்தினோம்.
        </p>
